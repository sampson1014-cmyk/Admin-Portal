const fs = require('node:fs'), path = require('node:path'), vm = require('node:vm'), assert = require('node:assert/strict');
const context = vm.createContext({ document: { addEventListener() {} } });
vm.runInContext(fs.readFileSync(path.join(__dirname, '../AdminGroupAssignment/wwwroot/js/migration-import.js'), 'utf8'), context);
let count = 0;
const check = (expression, expected) => { assert.equal(vm.runInContext(expression, context), expected); count++; };
const reject = expression => { assert.throws(() => vm.runInContext(expression, context)); count++; };
context.csv = 'Id,Description\r\n1,"Tea, cake"\r\n';
check('parseCsv(csv)[1][1]', 'Tea, cake');
context.csv = 'Id,Description\n1,"First\nSecond"';
check('parseCsv(csv)[1][1]', 'First\nSecond');
context.csv = 'Id,Description\n1,"A ""quote"""';
check('parseCsv(csv)[1][1]', 'A "quote"');
context.csv = 'Id,Description\n1,"Unclosed';
reject('parseCsv(csv)');
check('convertImportValue({name:"Password",type:"string",required:true}, "  unchanged  ")', '  unchanged  ');
check('convertImportValue({name:"Balance",type:"number",required:true}, "0")', 0);
check('convertImportValue({name:"Optional",type:"integer",required:false}, "")', null);
check('convertImportValue({name:"UseStampDiscount",type:"boolean",required:true}, "false")', false);
for (const value of ['abc', 'Infinity', '0x10']) reject(`convertImportValue({name:"Balance",type:"number",required:true}, ${JSON.stringify(value)})`);
reject('convertImportValue({name:"Point",type:"integer",required:true}, "1.5")');
reject('convertImportValue({name:"Point",type:"integer",required:true}, "2147483648")');
reject('convertImportValue({name:"Longitude",type:"number",required:true}, "678")');
reject('convertImportValue({name:"CreateDate",type:"date",required:true}, "yesterday")');
context.schema = { kind: 'members', fields: [{name:'UserId',type:'string',required:true},{name:'Name',type:'string',required:true}] };
reject('validateImportRows([["Unknown","Name"],["id","Lee"]],schema)');
reject('validateImportRows([["UserId","UserId"],["id","Lee"]],schema)');
reject('validateImportRows([["UserId"],["id"]],schema)');
check('validateImportRows([["UserId","Name"],["id","Lee"],["id","Lee"]],schema)[1].errors.length', 1);
check('validateImportRows([["UserId","Name"],["id","Lee","extra"]],schema)[0].errors.length', 1);
check('validateImportRows([["UserId","Name"],["id","Lee"]],schema)[0].data.UserId', 'id');
console.log(`${count} CSV migration checks passed. No API writes were made.`);
